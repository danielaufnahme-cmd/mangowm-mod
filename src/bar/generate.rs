//! Configuration and style generator for Mangobar.

use anyhow::Result;
use serde_json::{json, Map, Value};
use std::fs;
use std::path::{Path, PathBuf};

use super::model::Mangobar;
use crate::core::fsutil::atomic_write;

pub fn mangobar_dir() -> PathBuf {
    if let Ok(env) = std::env::var("MANGOBAR_MOD_DIR") {
        return PathBuf::from(env);
    }
    let base = dirs::config_dir().unwrap_or_else(|| PathBuf::from(".config"));
    base.join("mangobar").join("mango-mod")
}

pub fn generate_config(bar: &Mangobar) -> String {
    let mut map = Map::new();
    map.insert("position".into(), json!(bar.position));
    map.insert("height".into(), json!(bar.height));
    map.insert("spacing".into(), json!(bar.spacing));

    let m = if bar.floating { bar.margin } else { 0 };
    map.insert(
        "margin-top".into(),
        json!(if bar.position == "top" { m } else { 0 }),
    );
    map.insert(
        "margin-bottom".into(),
        json!(if bar.position == "bottom" { m } else { 0 }),
    );
    map.insert("margin-left".into(), json!(m));
    map.insert("margin-right".into(), json!(m));

    map.insert("modules-left".into(), json!(bar.modules.left));
    map.insert("modules-center".into(), json!(bar.modules.center));
    map.insert("modules-right".into(), json!(bar.modules.right));

    // Module definitions for Mangobar
    map.insert(
        "tag".into(),
        json!({
            "format": "{name}",
            "show-empty": false
        }),
    );
    map.insert(
        "layout".into(),
        json!({
            "format": "[{layout}]"
        }),
    );
    map.insert(
        "title".into(),
        json!({
            "format": "{}",
            "max-length": 45
        }),
    );
    map.insert(
        "clock".into(),
        json!({
            "format": "󰥔 {:%H:%M}",
            "tooltip-format": "{:%Y-%m-%d %A}"
        }),
    );
    map.insert(
        "cpu".into(),
        json!({
            "format": "󰻠 {usage}%",
            "interval": 2
        }),
    );
    map.insert(
        "memory".into(),
        json!({
            "format": "󰍛 {percentage}%",
            "interval": 2
        }),
    );
    map.insert(
        "volume".into(),
        json!({
            "format": "󰕾 {volume}%",
            "format-muted": "󰝟 muted"
        }),
    );
    map.insert(
        "battery".into(),
        json!({
            "format": "󰁹 {capacity}%",
            "format-charging": "󰂄 {capacity}%"
        }),
    );
    map.insert(
        "tray".into(),
        json!({
            "spacing": 8
        }),
    );

    let val = Value::Object(map);
    let body = serde_json::to_string_pretty(&val).unwrap_or_default();
    format!("// Generated by MangoWM Mod for Mangobar\n{}\n", body)
}

pub fn generate_style(bar: &Mangobar) -> String {
    format!(
        r#"/* Generated by MangoWM Mod for Mangobar */
* {{
    font-family: "Symbols Nerd Font", "JetBrainsMono Nerd Font", sans-serif;
    font-size: 13px;
}}

window#mangobar {{
    background-color: {bg};
    color: {fg};
    border-radius: {radius}px;
}}

#tag button {{
    padding: 0 6px;
    color: {fg};
    background: transparent;
}}

#tag button.active {{
    background-color: rgba(255, 255, 255, 0.16);
    border-radius: {btn_radius}px;
}}

#tag button.occupied {{
    color: #89b4fa;
}}

#layout,
#title,
#clock,
#cpu,
#memory,
#brightness,
#volume,
#battery,
#tray {{
    padding: 0 10px;
    margin: 3px 2px;
    background-color: rgba(255, 255, 255, 0.08);
    border-radius: {btn_radius}px;
}}
"#,
        bg = bar.bg_color,
        fg = bar.fg_color,
        radius = bar.radius,
        btn_radius = (bar.radius / 2).max(4)
    )
}

pub fn write_bar_files<P: AsRef<Path>>(bar: &Mangobar, dir: Option<P>) -> Result<PathBuf> {
    let out_dir = match dir {
        Some(d) => d.as_ref().to_path_buf(),
        None => mangobar_dir(),
    };
    fs::create_dir_all(&out_dir)?;

    let config_path = out_dir.join("config.jsonc");
    let style_path = out_dir.join("style.css");

    atomic_write(&config_path, &generate_config(bar))?;
    atomic_write(&style_path, &generate_style(bar))?;

    Ok(out_dir)
}

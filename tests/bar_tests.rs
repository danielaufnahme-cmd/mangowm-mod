#[test]
fn test_module_picker() {
    let mut m = mangowm_mod::bar::model::BarModules::default();
    m.left = vec!["workspaces".into()];
    m.center = vec!["clock".into()];
    m.right = vec!["cpu".into(), "memory".into()];
    m.add("right", "custom/power").unwrap();
    m.add("left", "battery#BAT1").unwrap();
    assert!(m.add("right", "cpu").is_err(), "duplicate");
    assert!(m.add("right", "nope").is_err());
    assert!(m.add("middle", "tray").is_err());
    assert_eq!(m.right, ["cpu", "memory", "custom/power"]);

    m.shift("right", 2, true).unwrap();
    assert_eq!(m.right, ["cpu", "custom/power", "memory"]);
    m.shift("right", 0, true).unwrap(); // first of a section: into the previous one
    assert_eq!(m.center, ["clock", "cpu"]);
    m.shift("left", 1, false).unwrap(); // last of a section: into the next one
    assert_eq!(m.center, ["battery#BAT1", "clock", "cpu"]);
    m.shift("left", 0, true).unwrap(); // already first in the bar: nothing
    assert_eq!(m.left, ["workspaces"]);
    assert_eq!(m.remove("right", 0).unwrap(), "custom/power");
    assert!(m.remove("right", 5).is_err());
    assert_eq!(m.right, ["memory"]);

    let mut bar = BarConfig::default();
    bar.modules = m;
    let v = parse(&generate_config(&bar));
    assert_eq!(
        v["modules-center"],
        serde_json::json!(["battery#BAT1", "clock", "cpu"])
    );
}


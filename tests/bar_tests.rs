use mangowm_mod::bar::generate::{generate_config, generate_style, warnings, write_bar_files};
use mangowm_mod::bar::model::{Backend, BarConfig, Mangobar};
use serde_json::Value;
use tempfile::tempdir;

/// Parse generated JSONC (only a leading `//` comment line is written).
fn parse(cfg: &str) -> Value {
    let body: String = cfg
        .lines()
        .filter(|l| !l.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n");
    serde_json::from_str(&body).unwrap()
}

fn full_bar(backend: Backend) -> BarConfig {
    let mut bar = BarConfig {
        backend,
        ..Default::default()
    };
    bar.set("left", "workspaces,layout,window,keymode").unwrap();
    bar.set("center", "clock#date,clock#time").unwrap();
    bar.set("right", "keyboardlayout,hideclients,network,cpu,memory,backlight,pulseaudio,battery,tray,custom/power").unwrap();
    bar
}

#[test]
fn test_mangobar_config_and_style() {
    let bar = full_bar(Backend::Mangobar);
    let cfg = generate_config(&bar);
    assert!(cfg.starts_with("// Generated by MangoWM Mod for Mangobar\n"));
    let v = parse(&cfg);
    assert_eq!(v["layer"], "top");
    assert_eq!(v["height"], 32);
    assert_eq!(
        v["modules-left"],
        serde_json::json!(["workspaces", "layout", "window", "keymode"])
    );
    assert_eq!(v["workspaces"]["hide-empty"], true);
    assert_eq!(v["workspaces"]["on-click"], "activate");
    assert_eq!(v["cpu"]["format"], " {load}%");
    assert_eq!(v["memory"]["format"], " {}%");
    assert_eq!(v["battery"]["format"], "{icon} {percent}%");
    assert!(v["battery"]["icons"].is_array());
    assert_eq!(v["pulseaudio"]["format"], "{icon} {volume}%");
    assert_eq!(v["tray"]["spacing"], 8);
    assert!(v["clock#date"]["format"].is_string());
    // no options block for modules not in use, none for modules without defaults
    assert!(v.get("custom/power").is_none());

    let css = generate_style(&bar);
    for id in [
        "#bar",
        "#tags",
        "#tags.active",
        "#tags.occupied",
        "#tags.urgent",
        "#tags.empty",
        "#overview",
        "#layout",
        "#title",
        "#keymode",
        "#clock",
        "#keyboardlayout",
        "#hideclients",
        "#network",
        "#cpu",
        "#mem",
        "#brightness",
        "#volume",
        "#battery",
        "#tray",
        "#custom-power",
    ] {
        assert!(css.contains(id), "missing {} in\n{}", id, css);
    }
    assert!(!css.contains("rgba("));
    assert!(css.contains("background-color: #1e1e2eeb"));
    assert!(!css.contains("#workspaces"));

    // only modules in use are styled
    let mut small = BarConfig::default();
    small.set("right", "clock").unwrap();
    small.set("left", "").unwrap();
    small.set("center", "").unwrap();
    let css = generate_style(&small);
    assert!(css.contains("#clock"));
    assert!(!css.contains("#cpu") && !css.contains("#tags"));
    let v = parse(&generate_config(&small));
    assert!(v.get("cpu").is_none());
}

#[test]
fn test_waybar_config_and_style() {
    let bar = full_bar(Backend::Waybar);
    let v = parse(&generate_config(&bar));
    assert_eq!(
        v["modules-left"],
        serde_json::json!([
            "mango/workspaces",
            "mango/layout",
            "mango/window",
            "mango/keymode"
        ])
    );
    let right = v["modules-right"].as_array().unwrap();
    assert!(right.contains(&"mango/language".into()));
    assert!(!right.contains(&"hideclients".into()));
    assert!(right.contains(&"custom/power".into()));
    assert_eq!(v["cpu"]["format"], " {usage}%");
    assert_eq!(v["memory"]["format"], " {percentage}%");
    assert_eq!(v["battery"]["format"], "󰁹 {capacity}%");
    assert_eq!(v["pulseaudio"]["format-muted"], "󰝟 muted");
    assert!(v["network"]["format-wifi"]
        .as_str()
        .unwrap()
        .contains("{essid}"));
    assert!(v.get("workspaces").is_none());

    let css = generate_style(&bar);
    assert!(css.contains("window#waybar"));
    assert!(css.contains("rgba(30, 30, 46, 0.9216)"));
    assert!(!css.contains("#1e1e2e"));
    for id in [
        "#workspaces button",
        "#workspaces button.active",
        "#workspaces button.urgent",
        "#workspaces button.empty",
        "#window",
        "#layout",
        "#keymode",
        "#language",
        "#clock",
        "#cpu",
        "#memory",
        "#backlight",
        "#pulseaudio",
        "#battery",
        "#network",
        "#tray",
        "#custom-power",
    ] {
        assert!(css.contains(id), "missing {} in\n{}", id, css);
    }
    assert!(!css.contains("#hideclients") && !css.contains("#tags"));
    let w = warnings(&bar);
    assert!(w.iter().any(|w| w.contains("hideclients")));
    assert!(w.iter().any(|w| w.contains("0.15.0")));
}

#[test]
fn test_waybar_without_mango_modules() {
    let mut bar = full_bar(Backend::Waybar);
    bar.set("waybar-mango-modules", "false").unwrap();
    let v = parse(&generate_config(&bar));
    assert_eq!(v["modules-left"], serde_json::json!(["ext/workspaces"]));
    let right = v["modules-right"].as_array().unwrap();
    assert!(!right
        .iter()
        .any(|m| m.as_str().unwrap().starts_with("mango/")));
    let w = warnings(&bar);
    for m in [
        "layout",
        "window",
        "keymode",
        "keyboardlayout",
        "hideclients",
        "ext/workspaces",
    ] {
        assert!(
            w.iter().any(|w| w.contains(m)),
            "no warning about {}: {:?}",
            m,
            w
        );
    }
    let css = generate_style(&bar);
    assert!(css.contains("#workspaces button"));
    assert!(!css.contains("#layout") && !css.contains("#language"));
    assert!(warnings(&BarConfig::default()).is_empty());
}

#[test]
fn test_bar_options_merge() {
    let mut bar = BarConfig::default();
    bar.set("clock.format", "{:L%H:%M:%S}").unwrap();
    bar.set("workspaces.pinned", "[1,2]").unwrap();
    bar.set("sys-interval", "5").unwrap();
    assert!(bar.set("clock.no-such-option", "1").is_err());
    assert!(bar.set("position", "bottom").is_err());
    let v = parse(&generate_config(&bar));
    assert_eq!(v["clock"]["format"], "{:L%H:%M:%S}");
    assert_eq!(v["workspaces"]["pinned"], serde_json::json!([1, 2]));
    assert_eq!(v["workspaces"]["hide-empty"], true);
    assert_eq!(v["sys-interval"], 5);

    let mut wb = BarConfig {
        backend: Backend::Waybar,
        ..Default::default()
    };
    wb.set("position", "bottom").unwrap();
    wb.set("workspaces.format", "{name}").unwrap();
    let v = parse(&generate_config(&wb));
    assert_eq!(v["position"], "bottom");
    assert_eq!(v["mango/workspaces"]["format"], "{name}");
}

#[test]
fn test_bar_config_round_trip() {
    let tmp = tempdir().unwrap();
    let path = BarConfig::default_path(tmp.path());
    assert_eq!(BarConfig::load(&path).unwrap(), Mangobar::default());

    let mut bar = BarConfig::default();
    bar.set("backend", "waybar").unwrap();
    bar.set("height", "28").unwrap();
    bar.set("bg", "#112233").unwrap();
    bar.set("accent", "rgba(255, 0, 0, 0.5)").unwrap();
    bar.set("font", "Inter").unwrap();
    bar.set("layer", "bottom").unwrap();
    bar.set("battery.format", "{capacity}").unwrap();
    bar.set("position", "bottom").unwrap();
    assert_eq!(bar.bg_color, "#112233ff");
    assert_eq!(bar.accent_color, "#ff000080");
    assert!(bar.set("layer", "middle").is_err());
    assert!(bar.set("left", "workspaces,nope").is_err());
    assert!(bar.set("bg", "blue").is_err());
    bar.save(&path).unwrap();
    let loaded = BarConfig::load(&path).unwrap();
    assert_eq!(loaded, bar);

    assert!(bar.unset("battery.format"));
    assert!(bar.unset("position"));
    assert!(!bar.unset("position"));
    assert!(bar.module_options.is_empty() && bar.options.is_empty());

    let dir = write_bar_files(&bar, Some(tmp.path().join("out"))).unwrap();
    assert!(dir.join("config.jsonc").is_file());
    assert!(dir.join("style.css").is_file());
}

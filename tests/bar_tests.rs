#[test]
fn test_start_at_login_writes_exec_once() {
    use mangowm_mod::bar::login::{is_login_command, login_state, set_login_start, LoginState};
    let tmp = tempdir().unwrap();
    std::fs::write(tmp.path().join("config.conf"), "border_px=2\n").unwrap();
    let mut mgr = manager(tmp.path());
    assert_eq!(login_state(&mgr), LoginState::Off);

    assert!(set_login_start(&mut mgr, true).unwrap());
    assert!(!set_login_start(&mut mgr, true).unwrap(), "only once");
    assert_eq!(login_state(&mgr), LoginState::Staged);
    mgr.apply().unwrap();
    assert_eq!(login_state(&mgr), LoginState::Applied);

    let text = std::fs::read_to_string(tmp.path().join("mango-mod.conf")).unwrap();
    let lines: Vec<&str> = text
        .lines()
        .filter(|l| l.starts_with("exec_once="))
        .collect();
    assert_eq!(lines.len(), 1, "{}", text);
    let cmd = lines[0].trim_start_matches("exec_once=");
    assert!(is_login_command(cmd), "{}", cmd);
    assert!(cmd.contains("mangowm-mod bar start"), "{}", cmd);
    // not the default data dir: the command says where the bar settings are
    assert!(
        cmd.ends_with(&format!(
            "--data-dir {}",
            tmp.path().join("data").display()
        )),
        "{}",
        cmd
    );
    // config.conf sources mango-mod.conf so the line is used
    let main = std::fs::read_to_string(tmp.path().join("config.conf")).unwrap();
    assert!(main.contains("source="), "{}", main);

    // other autostart entries are kept when it is turned off
    mgr.add_autostart("mako", false).unwrap();
    assert!(set_login_start(&mut mgr, false).unwrap());
    assert_eq!(login_state(&mgr), LoginState::Removing);
    mgr.apply().unwrap();
    let text = std::fs::read_to_string(tmp.path().join("mango-mod.conf")).unwrap();
    assert!(text.contains("exec_once=mako"));
    assert!(!text.contains("bar start"));

    assert!(is_login_command("/home/u/.local/bin/mangowm-mod bar start"));
    assert!(!is_login_command("mangowm-mod bar stop"));
    assert!(!is_login_command("waybar"));
}

